def q(s): return "'" + s.replace("'", "''") + "'"
def render(multiplier=1.0):
    """Return a complete menu, preserving the original prices and commands."""
    multiplier = validate_multiplier(multiplier)
    out = ["# AUTO-GENERATED by tools/make_spawnshop.py (MULT=%s). Edit the script, not this file." % multiplier,
           "menu_title: '&2&lSpawn Shop'", "open_command: shop", "size: 45", "update_interval: 1", "items:",
           "  balance:", "    material: GOLD_NUGGET", "    slot: 4", "    update: true",
           "    display_name: '&e&lYour money: &f$%vault_eco_balance_formatted%'",
           "    lore:", "      - '&7Earn money by doing your Jobs'", "      - '&7Click an item to buy it'",
           "  back:", "    material: ARROW", "    slot: 40", "    display_name: '&c&lBack to Menu'",
           "    left_click_commands:", "      - '[console] dm open server_menu %player_name%'",
           "    right_click_commands:", "      - '[console] dm open server_menu %player_name%'"]
    for key, slot, icon, name, give, amt, base, lore in ITEMS:
        p = price(base, multiplier)
        label = name if amt == 1 else f"{amt} {name}"
        acts = [f"[takemoney] {p}", f"[console] minecraft:give %player_name% {give} {amt}",
                f"[message] &aYou bought {label} for ${p}!", "[sound] ENTITY_EXPERIENCE_ORB_PICKUP", "[refresh]"]
        out += [f"  {key}:", f"    material: {icon}", f"    slot: {slot}", f"    amount: {min(amt,64)}",
                f"    display_name: {q('&a&l' + label)}",
                "    lore:", f"      - {q('&7' + lore)}", f"      - {q('&ePrice: &f$' + str(p))}", "      - '&8Tap or click to buy'"]
        for side in ("left", "right"):
            out += [f"    {side}_click_requirement:", "      requirements:",
                    "        money:", "          type: has money", f"          amount: {p}",
                    "          deny_commands:",
                    f"            - {q('[message] &cYou need $' + str(p) + ' for that. You have $%vault_eco_balance_formatted%. Keep working your Jobs!')}",
                    "            - '[sound] ENTITY_VILLAGER_NO'",
                    "        space:", "          type: string equals", "          input: '%player_has_empty_slot%'", "          output: 'yes'",
                    "          deny_commands:",
                    "            - '[message] &cYour inventory is full! Make some room first.'",
                    "            - '[sound] ENTITY_VILLAGER_NO'",
                    f"    {side}_click_commands:"] + [f"      - {q(a)}" for a in acts]
    return "\n".join(out) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("multiplier", nargs="?", default="1.0", help="positive price multiplier (default: 1.0)")
    parser.add_argument("--output", type=Path, default=Path("spawnshop.yml"), help="output file (default: spawnshop.yml in the current directory)")
    args = parser.parse_args(argv)
    try:
        multiplier = validate_multiplier(args.multiplier)
        menu = render(multiplier)
    except (ValueError, OverflowError) as exc:
        parser.error(str(exc))
    args.output.write_text(menu, encoding="utf-8")
    print(f"wrote {args.output} MULT={multiplier}")
    for key, slot, icon, name, give, amt, base, lore in ITEMS:
        print(f"{amt:>3} x {name:<24} ${price(base, multiplier)}")


if __name__ == "__main__":
    main()

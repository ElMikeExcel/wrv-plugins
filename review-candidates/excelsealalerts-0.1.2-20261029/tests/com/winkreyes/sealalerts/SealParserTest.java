package com.winkreyes.sealalerts;

import org.junit.jupiter.api.Test;
import java.nio.file.*;
import java.time.*;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;

class SealParserTest {
    static final ZoneId Z = ZoneId.of("America/Chicago");
    static long at(String hms) { return LocalDate.of(2026, 10, 24).atTime(LocalTime.parse(hms)).atZone(Z).toInstant().toEpochMilli(); }

    /** Replays a console log through the parser: "[HH:MM:SS] [..]: [Prefix] message". */
    static List<Map<String, Object>> replay(SealParser p, List<String> lines) {
        List<Map<String, Object>> out = new ArrayList<>();
        for (String ln : lines) {
            if (ln.length() < 10 || ln.charAt(0) != '[') continue;
            String t = ln.substring(1, 9);
            String plugin = null, msg = null;
            for (String[] pre : new String[][]{{"[SealLog] ", "ExcelSealLog"}, {"[ExcelGuildGate] ", "ExcelGuildGate"}, {"[ExcelBossTrial] ", "ExcelBossTrial"}}) {
                int i = ln.indexOf(pre[0]); if (i >= 0) { plugin = pre[1]; msg = ln.substring(i + pre[0].length()); break; }
            }
            if (plugin != null) p.accept(plugin, msg, at(t), out::add);
        }
        return out;
    }

    @Test void matchesSealwatchPy() throws Exception {
        // Fixture: the same lines run through sealwatch.py parse_lines (expected JSON generated by tests/gen_expected.py)
        Path dir = Path.of(System.getProperty("fixtures", "fixtures"));
        List<String> lines = Files.readAllLines(dir.resolve("parity.log"));
        String expected = Files.readString(dir.resolve("parity.expected.json")).trim();
        List<Map<String, Object>> got = replay(new SealParser(new Names("gamertag", null), Z), lines);
        assertEquals(expected, Json.of(got));
    }

    @Test void dragonSealBreakDoesNotDoubleEnd() {
        SealParser p = new SealParser(new Names("gamertag", null), Z);
        List<Map<String, Object>> out = replay(p, List.of(
            "[12:00:00] [Server thread/INFO]: [SealLog] FIGHT_START seal=dragon player=Steve_Test health=100% players=Steve_Test at=world_the_end@0,70,0",
            "[12:10:00] [Server thread/INFO]: [SealLog] BOSS_DEATH seal=dragon killer=Steve_Test players=Steve_Test at=world_the_end@0,70,0",
            "[12:10:01] [Server thread/INFO]: [ExcelGuildGate] Seal broken: ender_dragon (killer: Steve_Test) - 2 of 5 seals broken."));
        assertEquals(List.of("FIGHT_START", "FIGHT_END", "SEAL_BROKE"), out.stream().map(e -> e.get("type")).toList());
        assertEquals("2/5", out.get(2).get("count"));
    }

    @Test void bossTrialVerdicts() {
        SealParser p = new SealParser(new Names("gamertag", null), Z);
        List<Map<String, Object>> out = new ArrayList<>();
        long t = at("13:00:00");
        p.accept("ExcelBossTrial", "BossTrial announce [attempt] Steve_Test challenged The Wither.", t, out::add);
        p.accept("ExcelBossTrial", "BossTrial verdict DENY_SHARE: The Wither seal NOT credited (31.5% player damage, 1 present). Cooldown until 6h 0m from now; wither summons blocked / elder respawn queued as applicable.", t, out::add);
        p.accept("ExcelBossTrial", "BossTrial verdict DENY_COOLDOWN: The Wither kill was fought for but the seal is cooling down (5h 12m left).", t, out::add);
        p.accept("ExcelBossTrial", "BossTrial verdict CREDIT: The Ender Dragon seal earned (88.0% player damage, 2 champion(s) standing).", t, out::add);
        p.accept("ExcelBossTrial", "BossTrial burrow [The Warden]: only out-of-band or unattributed damage for 300s (total 10, counted 0) - the fight never came to it, so it digs away. No death, no verdict, no cooldown.", t, out::add);
        p.accept("ExcelBossTrial", "BossTrial encounter [An Elder Guardian] closed without a verdict: the boss is gone from its loaded area (no cooldown).", t, out::add);
        p.accept("ExcelBossTrial", "BossTrial elder progress: monument trio now 2 of 3 for this monument (90% player damage, 1 champion(s) standing).", t, out::add);
        p.accept("ExcelGuildGate", "Raid victory under Bad Omen level 3 - raid seal NOT credited (the seal requires Bad Omen level 5; no cooldown; a raid won at that omen still earns it).", t, out::add);
        p.accept("ExcelGuildGate", "[GuildGate] CONSOLE granted seal wither (2 of 5).", t, out::add);
        p.accept("ExcelGuildGate", "[GuildGate] CONSOLE reset catch-up for Some_Player to stage 0.", t, out::add); // not seal progress: ignored
        p.accept("ExcelBossTrial", "Wither summon blocked (skull place by Some_Player): seal cooldown, 5h left.", t, out::add); // ignored
        assertEquals(List.of("TRIAL_STARTED", "TRIAL_FAILED", "COOLDOWN_STARTED", "TRIAL_FAILED", "TRIAL_WON", "TRIAL_ENDED", "TRIAL_ENDED", "FIGHT_PROGRESS", "TRIAL_FAILED", "ADMIN_SEAL_CHANGE"),
                out.stream().map(e -> e.get("type")).toList());
        assertEquals("wither", out.get(0).get("fight"));
        assertEquals("6h 0m", out.get(2).get("length"));
        assertEquals("dragon", out.get(4).get("fight"));
        assertEquals("elder_guardian", out.get(6).get("fight"));
        assertTrue(p.cooldownAnnounced.containsKey("wither"));
    }

    @Test void twoVerdictsSameMomentOneCooldown() {
        SealParser p = new SealParser(new Names("gamertag", Map.of()), Z);
        List<Map<String, Object>> out = new ArrayList<>();
        String v = "BossTrial verdict DENY_SHARE: The Wither seal NOT credited (0.0% player damage, 0 present). Cooldown until 6h 0m from now; wither summons blocked / elder respawn queued as applicable.";
        p.accept("ExcelBossTrial", v, at("13:37:33"), out::add);
        p.accept("ExcelBossTrial", v, at("13:37:33"), out::add);
        assertEquals(2, out.stream().filter(e -> "TRIAL_FAILED".equals(e.get("type"))).count());
        assertEquals(1, out.stream().filter(e -> "COOLDOWN_STARTED".equals(e.get("type"))).count());
    }

    @Test void reloadSwitchesNameMode() {
        SealParser p = new SealParser(new Names("gamertag", Map.of()), Z);
        List<Map<String, Object>> out = new ArrayList<>();
        p.accept("ExcelGuildGate", "Seal broken: wither (killer: Steve_Test) - 2 of 5 seals broken.", at("10:00:00"), out::add);
        int before = out.size();
        p.names(new Names("hidden", Map.of()));
        p.accept("ExcelGuildGate", "Seal broken: warden (killer: Steve_Test) - 3 of 5 seals broken.", at("10:01:00"), out::add);
        assertEquals("Steve_Test", out.get(0).get("killer"));
        assertTrue(out.stream().skip(before).noneMatch(e -> String.valueOf(e).contains("Steve_Test")), String.valueOf(out));
    }

    @Test void labelModeHidesGamertags() {
        SealParser p = new SealParser(new Names("label", Map.of("Steve_Test", "Parent")), Z);
        List<Map<String, Object>> out = new ArrayList<>();
        p.accept("ExcelSealLog", "BOSS_SPAWN seal=wither reason=BUILD_WITHER nearby=Steve_Test,.BedrockTest1 at=world@1,2,3", at("10:00:00"), out::add);
        p.accept("ExcelGuildGate", "Seal broken: wither (killer: .BedrockTest1) - 2 of 5 seals broken.", at("10:05:00"), out::add);
        String j = Json.of(out);
        assertFalse(j.contains("BedrockTest1"), j); assertFalse(j.contains("Steve_Test"), j);
        assertTrue(j.contains("Parent"), j); assertTrue(j.contains("Player-"), j);
    }

    @Test void idleFightClosesAfterAnHour() {
        SealParser p = new SealParser(new Names("gamertag", null), Z);
        List<Map<String, Object>> out = new ArrayList<>();
        p.accept("ExcelSealLog", "BOSS_EMERGE seal=warden reason=NATURAL nearby=A at=world@0,0,0", at("10:00:00"), out::add);
        p.sweep(at("10:30:00"), out::add); assertEquals(1, out.size());
        p.sweep(at("11:00:01"), out::add); assertEquals("FIGHT_END", out.get(1).get("type"));
        assertTrue(p.openFights().isEmpty());
    }
}

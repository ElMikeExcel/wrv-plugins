package com.winkreyes.excelmagicgate;

import org.yaml.snakeyaml.Yaml;

import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;

/**
 * The offline placement calculator (DESIGN.md S8) — a TEST-CLASSPATH
 * tool, never shipped in the jar. Reads a folder of Magic mage .dat
 * files (a fresh panel pull), computes each mage's credited total
 * under the classification carried by the shipped config.yml, prints
 * the placement table, and writes the pre-placement earned.yml the
 * install packet drops into plugins/ExcelMagicGate/ BEFORE the jar
 * swap.
 *
 * Usage: PlacementTool <datDir> <config.yml> <outEarned.yml> <sourceLabel> <date>
 */
public final class PlacementTool {

    public static void main(String[] args) throws Exception {
        Path datDir = Path.of(args[0]);
        Path configFile = Path.of(args[1]);
        Path out = Path.of(args[2]);
        String source = args[3];
        String date = args[4];

        CreditPolicy policy;
        try (InputStream in = Files.newInputStream(configFile)) {
            Map<String, Object> root = new Yaml().load(in);
            @SuppressWarnings("unchecked")
            Map<String, Object> earning = (Map<String, Object>) root.get("earning");
            policy = policyFrom(earning);
        }

        EarnedStore store = new EarnedStore();
        Map<String, String> names = new TreeMap<>();
        try (var stream = Files.list(datDir)) {
            List<Path> files = stream
                    .filter(f -> f.getFileName().toString().endsWith(".dat"))
                    .sorted().toList();
            for (Path f : files) {
                String uuid = f.getFileName().toString().replace(".dat", "");
                Map<String, Object> dat;
                try (InputStream in = Files.newInputStream(f)) {
                    dat = new Yaml().load(in);
                }
                if (dat == null) {
                    continue;
                }
                @SuppressWarnings("unchecked")
                Map<String, Object> spells = (Map<String, Object>) dat.getOrDefault("spells", Map.of());
                long raw = PlacementCalculator.rawTotal(spells);
                long credited = PlacementCalculator.creditedTotal(spells, policy);
                store.seedPlacement(uuid, credited);
                names.put(uuid, String.valueOf(dat.getOrDefault("name", "?")));
                System.out.printf("%-40s %-18s raw=%-7d credited=%-7d -> %s%n",
                        uuid, names.get(uuid), raw, credited,
                        EarnedRank.rankFor(credited, EarnedRank.Thresholds.locked()).key());
            }
        }
        store.markPlacementDone(date, source);

        // Serialize through the EarnedStore codec shape, via SnakeYAML.
        String yaml = new Yaml().dump(store.toMap());
        Files.writeString(out, "# ExcelMagicGate earned.yml - placement pre-write ("
                + source + ", " + date + ")\n"
                + "# Generated by the offline placement calculator (DESIGN.md S8) from a\n"
                + "# read-only pull of plugins/Magic/data/players. Placement is a one-time\n"
                + "# record: the live plugin never recomputes it.\n" + yaml);
        System.out.println("wrote " + out + " (" + store.playersTracked() + " players)");
    }

    private static CreditPolicy policyFrom(Map<String, Object> earning) {
        java.util.function.Function<String, Set<String>> set = key -> {
            Object v = earning.get(key);
            java.util.Set<String> s = new java.util.LinkedHashSet<>();
            if (v instanceof List<?> list) {
                for (Object o : list) {
                    s.add(String.valueOf(o).trim().toLowerCase(java.util.Locale.ROOT));
                }
            }
            return s;
        };
        int cap = earning.get("daily-cap-per-family") instanceof Number n ? n.intValue() : 50;
        int pair = earning.get("pair-window-max") instanceof Number n ? n.intValue() : 5;
        return new CreditPolicy(set.apply("no-credit-families"), set.apply("heal-gate-families"),
                set.apply("damage-strict-families"), set.apply("damage-correlated-families"),
                set.apply("target-gate-families"), cap, pair);
    }
}
